// Writes the benchmark workflows (one file per mode, each under the 256-job matrix limit). Run once; the output is
// committed and reviewed. Security requirements are in bench/PROTOCOL.md, "Execution environment".
import { writeFileSync } from "node:fs";
const CHECKOUT = "actions/checkout@11d5960a326750d5838078e36cf38b85af677262 # v4";
const SETUP_NODE = "actions/setup-node@49933ea5288caeca8642d1e84afbd3f7d6820020 # v4";
const UPLOAD = "actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02 # v4.6.2";
const head = (name) => `# GENERATED by bench/gen-workflows.mjs: do not edit by hand.
name: ${name}
on:
  pull_request:
    branches: ["goat/signal"]
permissions: {}
concurrency:
  group: ${name}-\${{ github.event.pull_request.number }}
  cancel-in-progress: false
jobs:
  plan:
    runs-on: ubuntu-24.04
    timeout-minutes: 5
    outputs:
      ids: \${{ steps.p.outputs.ids }}
    steps:
      - uses: ${CHECKOUT}
        with:
          persist-credentials: false
      - id: p
        run: node bench/plan.mjs ${name.replace("bench-", "")} >> "$GITHUB_OUTPUT"
`;
for (const mode of ["signal", "ref-base", "ref-head", "lastgreen"]) {
  const y = head(`bench-${mode}`) + `  case:
    needs: plan
    if: needs.plan.outputs.ids != '[]'
    runs-on: ubuntu-24.04
    timeout-minutes: 60
    strategy:
      fail-fast: false
      matrix:
        id: \${{ fromJSON(needs.plan.outputs.ids) }}
    steps:
      - uses: ${CHECKOUT}
        with:
          persist-credentials: false
      - id: node
        env:
          CASE_ID: \${{ matrix.id }}
        run: echo "spec=$(node bench/extract-case.mjs "$CASE_ID" | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>console.log(JSON.parse(s).node))')" >> "$GITHUB_OUTPUT"
      - id: setup
        continue-on-error: true
        uses: ${SETUP_NODE}
        with:
          node-version: \${{ steps.node.outputs.spec }}
      - name: Run case in sandbox
        env:
          CASE_ID: \${{ matrix.id }}
          SETUP_OK: \${{ steps.setup.outcome }}
        run: |
          mkdir -p bench-out
          if [ "$SETUP_OK" != "success" ]; then echo '{"case_id":"'"$CASE_ID"'","mode":"${mode}","errors":["node version spec could not be installed"],"env_failure":true}' > bench-out/result.json; exit 0; fi
          bash bench/sandbox.sh ${mode} "$CASE_ID"
      - if: always()
        uses: ${UPLOAD}
        with:
          name: res-${mode}-\${{ matrix.id }}
          path: bench-out/
          retention-days: 30
          if-no-files-found: warn
`;
  writeFileSync(`.github/workflows/bench-${mode}.yml`, y);
}
writeFileSync(".github/workflows/bench-freeze-ci.yml", head("bench-freeze-ci") + `  shard:
    needs: plan
    if: needs.plan.outputs.ids != '[]'
    runs-on: ubuntu-24.04
    timeout-minutes: 30
    strategy:
      fail-fast: false
      matrix:
        shard: \${{ fromJSON(needs.plan.outputs.ids) }}
    steps:
      - uses: ${CHECKOUT}
        with:
          persist-credentials: false
      # reads public CI data only; no project code runs in this workflow
      - env:
          GITHUB_TOKEN: \${{ github.token }}
          SHARD: \${{ matrix.shard }}
        run: node bench/freeze-ci.mjs bench/candidates.json "$SHARD" 25 "ci-$SHARD.json"
      - uses: ${UPLOAD}
        with:
          name: ci-\${{ matrix.shard }}
          path: ci-*.json
          retention-days: 30
`);
